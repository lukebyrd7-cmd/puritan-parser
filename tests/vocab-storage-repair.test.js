const test = require('node:test');
const assert = require('node:assert/strict');

global.state = { prefs: { initialEase: 2.5 } };
global.todayISO = () => '2026-08-03';
global.createUserProgress = value => value;
const storage = require('../src/core/storage/vocab-storage');

test('synthetic legacy schedules are removed only when the exact default tuple has no user evidence', () => {
  const synthetic = { id: 'lemma:greek:a', ease: 2.5, interval: 0, repetitions: 0, due: '2026-08-02', history: [], parsing: { attempts: 0, correct: 0, streak: 0, misses: {}, todayMisses: [] }, vocab: { attempts: 0, correct: 0 } };
  const legitimate = { id: 'lemma:greek:b', ease: 2.5, interval: 1, repetitions: 0, due: '2026-08-04', history: [{ date: '2026-08-03', q: 2 }] };
  const custom = { ...synthetic, id: 'lemma:greek:c', customGloss: 'custom' };
  const repaired = storage.repairSyntheticDefaultSchedules([synthetic, legitimate, custom]);
  assert.equal(repaired.changed, true);
  assert.deepEqual(repaired.items[0], legitimate);
  assert.equal(repaired.items[1].id, custom.id);
  assert.equal(repaired.items[1].customGloss, 'custom');
  assert.equal('due' in repaired.items[1], false);

  const second = storage.repairSyntheticDefaultSchedules(repaired.items);
  assert.equal(second.changed, false);
  assert.deepEqual(second.items, repaired.items);
});

test('imported words remain persisted while autogenerated schedule fields are omitted', () => {
  const imported = { id: 'imported-1', source: 'Imported', word: 'λόγος', gloss: 'word', ease: 2.5, interval: 0, repetitions: 0, due: '2026-08-03', history: [] };
  const compact = storage.compactProgressItem(imported);
  assert.equal(compact.word, 'λόγος');
  for(const key of ['ease','interval','repetitions','due','history']) assert.equal(key in compact, false);
});
